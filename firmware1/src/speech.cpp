//
// PROGMEM을 붙이면 플래시(256KB)에만 올라가고 RAM(8KB)은 쓰지 않습니다.
// 붙이지 않으면 부팅할 때 RAM으로 복사되어 256바이트를 잡아먹습니다.
// 나중에 오디오 버퍼를 잡아야 하므로 RAM은 아껴 둡니다.
