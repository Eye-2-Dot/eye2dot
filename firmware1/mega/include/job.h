/*
 * Eye 2 Dot — 펌웨어 1 (라벨 출력기)
 * job.h — 작업 진행 (상태 기계: 지금 상태에 따라 할 일을 나누는 구조)
 *
 * 촬영 버튼으로 ESP32 에 촬영을 요청하고, ESP32 가 보낸 작업(점자 + 음성)을
 * 안내 재생 → 출력 버튼 → 타각(punch) → ESP32 에 'D'(완료) 까지 진행합니다.
 * 그 밖에 맡는 것: ESP32 알림음 프레임 → 실패음, 시간 초과, 상태 LED
 *
 * ── 상태와 버튼 ──
 *   상태       │ 촬영 버튼 (D31)                    │ 출력 버튼 (D32)
 *   ──────────┼───────────────────────────────────┼──────────────────────────────
 *   대기       │ 'C' + 준비음 → 인식 중               │ 잘못 누름 소리
 *   인식 중    │ 무시                                │ 무시
 *   안내 재생  │ 음성 멈춤 → 'E' → 'C' + 준비음 → 인식 중 │ 음성 멈추고 바로 타각
 *              │                                    │ (점자 없는 작업이면 무시)
 *   출력 대기  │ 'E' → 'C' + 준비음 → 인식 중          │ 타각
 *   타각 중    │ 무시                                │ 무시
 *
 *   저절로 바뀌는 경우
 *     - 새 점자 프레임이 오면 어느 상태에서든 지금 작업을 정리하고 → 안내 재생
 *       (촬영 결과와 앱 작업이 같다. 'C' 와 앱 작업이 엇갈려 앱 작업이 먼저 와도 그대로 갈아탄다)
 *     - 인식 중에 ESP32 알림음(촬영·서버 실패)이 오거나 LINK_RECOGNIZE_TIMEOUT_MS 가 지나면
 *       → 실패음 → 대기
 *     - 안내 재생이 끝나면 → 출력 대기. 점자가 없는 작업(실패 안내)이면 → 'D' → 대기
 *     - 안내 재생·출력 대기가 점자 프레임을 받은 뒤 LINK_JOB_TIMEOUT_MS 를 넘기면
 *       → 'E' + 실패음 → 대기
 *     - 타각 성공 → 'D' + 완료음 → 대기,  타각 실패 → 'E' + 실패음 → 대기
 *
 * ── link · speech · job 의 경계 ──
 *   link   = 음성 파이프. 프레임이 도착한 "그 순간"에 해야 하는 일을 합니다.
 *              음성 시작 → speechStreamBegin, 조각 → speechStreamWrite, 끝 → speechStreamEnd
 *              링 버퍼에 자리가 있을 때만 'R' 로 다음 조각 요청 (흐름 제어)
 *              새 점자 프레임이 오면 이전 작업의 음성 정지
 *            이 일들은 다음 프레임이 같은 버퍼를 덮어쓰기 전에 끝나야 하므로 link 안에 둡니다.
 *            (job 이 나중에 하면, 같은 linkPoll 안에서 이미 시작된 새 음성까지 멈출 수 있음)
 *   speech = 소리 내기 (타이머, 링 버퍼, 소리 신호)
 *   job    = 정책. 언제 음성을 멈추고(speechStop + linkAudioAbort),
 *            언제 버튼을 받고, 언제 'C'/'D'/'E' 를 보낼지 정합니다.
 *            음성 수신 과정에는 끼어들지 않고 결과(linkAudioState, speechStreamFinished)만 봅니다.
 */

#ifndef JOB_H
#define JOB_H

#include <Arduino.h>

/* setup() 에서 한 번. 상태 LED 핀을 준비합니다. */
void jobInit();

/*
 * loop() 에서 매번 부릅니다 (delay() 없음). buttonsUpdate() 다음에 부르세요.
 *   ESP32 알림음 → 실패음, 새 작업, 버튼, 재생 끝, 시간 초과, LED
 */
void jobUpdate(uint32_t now);

/* 대기가 아닌지 (console 이 소리 시험 명령을 막을 때 씀) */
bool jobIsActive();

/* 지금 상태 이름 (console 의 상태 출력용) */
const __FlashStringHelper* jobStateName();

#endif  // JOB_H
