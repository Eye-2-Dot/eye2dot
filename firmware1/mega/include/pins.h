/*
 * Eye 2 Dot — 펌웨어 1 (라벨 출력기)
 * pins.h — 핀 번호 상수 모음 (팀 공용)
 *
 * 팀 핀 배치표를 그대로 옮긴 파일입니다.
 * 배선이 바뀌면 이 파일만 고치면 모든 모듈에 반영됩니다.
 *
 * 이 헤더는 다른 헤더에 의존하지 않습니다(Arduino.h 제외).
 * 누가 어느 모듈에서 include 해도 충돌이 없도록 하기 위함입니다.
 *
 * 괄호 안의 PB5, PA0 같은 표기는 칩 내부 포트 이름입니다(데이터시트 표기).
 */

#ifndef PINS_H
#define PINS_H

#include <Arduino.h>

// ─────────────────────────────────────────────
// 사용 금지 — 새 모듈을 만들기 전에 반드시 읽을 것
// ─────────────────────────────────────────────
// Timer1·Timer2 는 오디오 전용입니다(speech.cpp).
//   Timer1 = 62.5kHz PWM 캐리어(소리를 싣는 바탕 신호), 출력은 D11
//   Timer2 = 8kHz 샘플 인터럽트(1/8000초마다 다음 소리 값을 넣는 신호)
// 아래 기능은 이 타이머를 건드려서 소리를 망가뜨립니다.
//   - tone()                 : Timer2 를 통째로 가져갑니다
//   - D9, D10 의 analogWrite : Timer2 를 씁니다.
//       특히 D10 은 OCR2A 를 바꿔서 샘플레이트(재생 속도)가 달라집니다
//   - D11, D12 의 analogWrite: Timer1 을 씁니다. D11 은 오디오 출력 핀 자체입니다
// Timer0 도 설정을 바꾸면 안 됩니다. millis(), delay() 가 Timer0 으로 돕니다.
// D0, D1 은 USB 시리얼(Serial)이 씁니다. 다른 용도로 쓰지 마세요.

// ─────────────────────────────────────────────
// 오디오 (담당: 오디오 모듈)
// ─────────────────────────────────────────────
// 핀 11 = PB5 = OC1A.
// Timer1의 하드웨어 PWM 출력이 나오는 핀이라 반드시 이 번호여야 합니다.
// 다른 핀으로 옮기면 Timer1 PWM을 쓸 수 없습니다.
//   핀 11 → 1kΩ → (0.047µF to GND) → 10µF 직렬 → LM386 모듈 → 스피커
constexpr uint8_t PIN_AUDIO = 11;

// ─────────────────────────────────────────────
// ESP32-CAM 통신 (UART1 = Serial1)
// ─────────────────────────────────────────────
// 코드에서는 Serial1 객체로 씁니다(link.cpp). AVR 에서는 Serial1 의 핀이 D19·D18 로
// 고정되어 있어서, 아래 두 상수는 코드에서 쓰지 않는 배선 안내용입니다.
// pinMode 도 Serial1.begin() 이 알아서 합니다.
//
// ESP32-CAM 은 3.3V, Mega 는 5V 라서 Mega → ESP32 방향은 전압을 낮춰야 합니다.
//   ESP32-CAM GPIO15(TX) ────────────▶ D19(RX1)          직결 (3.3V 도 HIGH 로 인식됨)
//
//   D18(TX1) ──[1kΩ]──┬──▶ ESP32-CAM GPIO14(RX)          5V × 2/3 ≈ 3.3V
//                     │
//                   [2kΩ]
//                     │
//                    GND
//   GND 는 반드시 공통
constexpr uint8_t PIN_LINK_RX = 19;   // PD2, ATmega 가 받는 핀(RX1) ← ESP32-CAM GPIO15(TX) 직결
constexpr uint8_t PIN_LINK_TX = 18;   // PD3, ATmega 가 보내는 핀(TX1) → 1kΩ+2kΩ 분압 → ESP32-CAM GPIO14(RX)

// ─────────────────────────────────────────────
// 점자 셀 솔레노이드 6개 (담당: 세연)
// ─────────────────────────────────────────────
// 솔레노이드 1~6 = 핀 22~27 = PA0~PA5. 한 포트에 연속으로 몰아둔 배치라
// 나중에 PORTA 한 번 쓰기로 6핀을 동시에 제어할 수 있습니다.
//
// 주의: 헤더에 정의된 const 배열은 include 하는 .cpp 마다
//       복사본이 생깁니다(파일당 6바이트). 안 쓰는 파일에서는
//       컴파일러가 제거하므로 실제 RAM 부담은 없습니다.
constexpr uint8_t PIN_SOL[6] = { 22, 23, 24, 25, 26, 27 };

// ─────────────────────────────────────────────
// 스텝 모터 2개 (담당: 준석)
// ─────────────────────────────────────────────
// STEP : 펄스 하나에 한 스텝 이동
// DIR  : 회전 방향
// EN   : 드라이버 켜기/끄기 (A4988·DRV8825 계열은 LOW 일 때 켜짐)
constexpr uint8_t PIN_HEAD_STEP = 36;   // PC1, 스텝 A (헤드 이동) STEP
constexpr uint8_t PIN_HEAD_DIR  = 37;   // PC0, 스텝 A (헤드 이동) DIR
constexpr uint8_t PIN_HEAD_EN   = 38;   // PD7, 스텝 A (헤드 이동) EN

constexpr uint8_t PIN_TAPE_STEP = 40;   // PG1, 스텝 B (테이프 이송) STEP
constexpr uint8_t PIN_TAPE_DIR  = 41;   // PG0, 스텝 B (테이프 이송) DIR
constexpr uint8_t PIN_TAPE_EN   = 42;   // PL7, 스텝 B (테이프 이송) EN

// L298N 임시 연결 메모
//   STEP/DIR 드라이버가 오기 전까지 L298N 으로 시험할 때의 배선입니다.
//   L298N 은 코일 4선(IN1~IN4)을 직접 제어하므로 핀 4개씩 씁니다.
//     스텝 A(헤드)   = D36~D39 → IN1~IN4
//     스텝 B(테이프) = D40~D43 → IN1~IN4
//   이 동안에는 위의 STEP/DIR/EN 상수 대신 이 네 핀을 쓰고,
//   D39·D43 은 다른 용도로 쓰지 마세요.

// ─────────────────────────────────────────────
// 조작 버튼 (INPUT_PULLUP)
// ─────────────────────────────────────────────
// INPUT_PULLUP = 칩 내부 저항으로 평소에 HIGH 를 유지하는 입력 모드.
// 버튼 한쪽은 핀, 다른 쪽은 GND 에 연결합니다. 누르면 LOW 가 됩니다.
// 전원은 배터리 선의 물리 스위치로 켜고 끕니다(핀 없음).
constexpr uint8_t PIN_BTN_CAPTURE = 31;   // PC6, 촬영·재촬영 버튼
constexpr uint8_t PIN_BTN_PRINT   = 32;   // PC5, 출력 버튼

// ─────────────────────────────────────────────
// 센서
// ─────────────────────────────────────────────
constexpr uint8_t PIN_HEAD_LIMIT   = 34;   // PC3, 헤드 원점 리밋 스위치
constexpr uint8_t PIN_LABEL_SENSOR = 35;   // PC2, 라벨 위치 센서 (선택 사항)

// ─────────────────────────────────────────────
// 상태 표시
// ─────────────────────────────────────────────
constexpr uint8_t PIN_LED = 13;   // 보드 내장 LED (PB7)

#endif  // PINS_H
