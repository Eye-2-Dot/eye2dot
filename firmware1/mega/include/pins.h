/*
 * Eye 2 Dot — 펌웨어 1 (라벨 출력기)
 * pins.h — 핀 번호 상수 모음 (팀 공용)
 *
 * 팀 핀 배치표를 그대로 옮긴 파일입니다.
 * 배선이 바뀌면 이 파일만 고치면 모든 모듈에 반영됩니다.
 *
 * 이 헤더는 다른 헤더에 의존하지 않습니다(Arduino.h 제외).
 * 누가 어느 모듈에서 include 해도 충돌이 없도록 하기 위함입니다.
 */

#ifndef PINS_H
#define PINS_H

#include <Arduino.h>

// ─────────────────────────────────────────────
// 오디오 (담당: 오디오 모듈)
// ─────────────────────────────────────────────
// 핀 11 = PB5 = OC1A.
// Timer1의 하드웨어 PWM 출력이 나오는 핀이라 반드시 이 번호여야 합니다.
// 다른 핀으로 옮기면 Timer1 PWM을 쓸 수 없습니다.
//   핀 11 → RC 필터 → LM386 앰프 → 스피커
constexpr uint8_t PIN_AUDIO = 11;

// ─────────────────────────────────────────────
// 점자 셀 솔레노이드 6개 (담당: 세연)
// ─────────────────────────────────────────────
// 핀 22~27 = PA0~PA5. 한 포트에 연속으로 몰아둔 배치라
// 나중에 PORTA 한 번 쓰기로 6핀을 동시에 제어할 수 있습니다.
//
// 주의: 헤더에 정의된 const 배열은 include 하는 .cpp 마다
//       복사본이 생깁니다(파일당 6바이트). 안 쓰는 파일에서는
//       컴파일러가 제거하므로 실제 RAM 부담은 없습니다.
constexpr uint8_t PIN_SOL[6] = { 22, 23, 24, 25, 26, 27 };

// ─────────────────────────────────────────────
// 이송부 (담당: 준석)
// ─────────────────────────────────────────────
constexpr uint8_t PIN_SERVO = 28;   // PA6, 서보 신호
constexpr uint8_t PIN_LIMIT = 34;   // PC3, 리밋 스위치 (원점 검출)

// ─────────────────────────────────────────────
// 조작 버튼
// ─────────────────────────────────────────────
constexpr uint8_t PIN_BTN_MODE   = 31;   // PC6, 모드 전환
constexpr uint8_t PIN_BTN_OK     = 32;   // PC5, 확인
constexpr uint8_t PIN_BTN_CANCEL = 33;   // PC4, 취소

// ─────────────────────────────────────────────
// 상태 표시
// ─────────────────────────────────────────────
constexpr uint8_t PIN_LED = 13;   // 보드 내장 LED (PB7)

#endif  // PINS_H
