/*
 * Eye 2 Dot — 펌웨어 1 (라벨 출력기)
 * punch.h — 점자 타각 (라벨 한 장 찍기)
 *
 * ── 구조 ──
 *   punch    = 라벨 한 장 찍는 순서
 *              헤드 원점 → 카드 한 장 공급 → 칸마다 헤드 이동 + 솔레노이드 → 헤드 원점 자리로 → 랙 되돌리기
 *   solenoid = 핀 6개 누르기              (세연, solenoid.h)
 *   stepper  = 헤드·카드 랙 움직이기       (stepper.h, 조정값은 motion.h)
 *
 * punch 는 solenoid·stepper 를 불러 순서만 짜고, 핀을 직접 만지지 않습니다.
 *
 * ── 기구 (A 방식: 카드 정지 / 헤드 이동) ──
 *   카드 랙(모터 B)이 적층함 맨 아래 카드 한 장을 고정 벽까지 밀어 놓으면,
 *   카드는 그 자리에 가만히 있고 헤드(모터 A)가 칸마다 6mm 씩 옮겨 가며 찍습니다.
 *   찍는 동안 랙은 카드를 받치고 있다가, 다 찍으면 영점으로 돌아갑니다.
 *   찍힌 카드는 사람이 꺼냅니다 (꺼내지 않으면 다음 카드가 걸립니다).
 *
 * ── 찍는 방향 (팀 약속 — stepper 를 만들 때 이대로) ──
 *   - 솔레노이드는 라벨을 위에서 아래로 찍습니다. 점은 아랫면으로 튀어나오므로
 *     사람은 라벨을 좌우로 뒤집어 읽습니다.
 *   - 줄의 첫 칸 job.cells[줄][0] 을 위에서 볼 때 **오른쪽 끝**에 찍고, 칸마다 **왼쪽으로** 진행합니다.
 *     라벨은 한 줄입니다 (카드 한 장 = 한 줄, 최대 LABEL_MAX_CELLS 칸 — motion.h).
 *     원점 스위치가 오른쪽 끝에 있으면 원점 쪽 칸부터, 왼쪽 끝에 있으면 먼 칸부터 찍습니다
 *     (motion.h 의 HEAD_HOME_AT_RIGHT).
 *     → 뒤집어 읽으면 첫 칸이 왼쪽 끝에 와서 순서가 맞습니다.
 *   - 솔레노이드 1번(D22) = 위에서 볼 때 왼쪽 위. 1·2·3 왼쪽 열, 4·5·6 오른쪽 열 (위→아래).
 *   - 칸 안의 좌우는 서버가 이미 바꿔서 보냅니다(거울 값). 펌웨어는 칸 값·칸 순서를 뒤집지 않습니다.
 *
 * 부르는 쪽: job — 타각할 때가 되면 punchBraille() 을 부르고,
 *            결과에 따라 ESP32 에 'D'(완료) 또는 'E'(실패)를 보냅니다.
 */

#ifndef PUNCH_H
#define PUNCH_H

#include <Arduino.h>

#include "link.h"   // BrailleJob

/*
 * setup() 맨 처음에 한 번 (main.cpp). 솔레노이드 핀을 출력으로 만들고 모두 끄고,
 * 스텝 모터 핀을 출력으로 만들어 두 모터를 꺼 둡니다.
 * Serial.begin() 보다 먼저 불리므로 이 안에서는 Serial 로그를 쓰지 마세요.
 */
void punchInit();

/*
 * 점자 한 장을 찍습니다.
 *
 *   넘겨받는 것 : job.lineCount       줄 수 (라벨은 1)
 *                 job.lineLen[줄]     그 줄의 칸 수
 *                 job.cells[줄][칸]   칸 값 = 서버가 거울로 바꾼 6비트 값 = 솔레노이드 비트
 *                                     bit0 = 솔레노이드 1번, bit1 = 2번, bit2 = 3번,
 *                                     bit3 = 4번, bit4 = 5번, bit5 = 6번
 *                                     (1번 = 위에서 볼 때 왼쪽 위, 위 "찍는 방향" 참고)
 *                 (구조체는 include/link.h, 크기 한도는 common/protocol.h 의 BRAILLE_MAX_*)
 *   솔레노이드  : pins.h 의 PIN_SOL[0..5] = 솔레노이드 1..6 (D22~D27)
 *   돌려줄 값   : 다 찍었으면 true  → ESP32 에 'D'
 *                 실패하면 false → 'E'. 실패하는 경우:
 *                   - 헤드 원점을 못 잡음 (스위치 배선·방향·걸림)
 *                   - 카드에 안 들어감 (두 줄 이상, 또는 LABEL_MAX_CELLS 칸 초과)
 *                   - 카드 감지 센서를 달았는데 카드가 안 보임 (적층함이 비었거나 걸림)
 *                   - 움직이는 도중에 멈춤 요청이 옴 (버튼·USB)
 *                 실패하면 아무것도 찍지 않거나 찍다 만 채로 모터를 끄고 돌아옵니다.
 *   걸리는 시간 : 보통 30~50초, 전원을 켠 뒤 첫 장은 약 15초 더. 가장 길 때 약 110초
 *                 (모터가 28BYJ-48 이라 느리다. punch.cpp 의 static_assert 가 계산).
 *                 ESP32 가 'D' 를 기다리는 시간(common/protocol.h)이 이보다 길어야 합니다.
 *   멈추기      : 움직이는 동안 버튼을 뗐다가 다시 누르거나 USB 로 아무 글자나 보내면
 *                 즉시 멈추고 false 를 돌려줍니다 (stepper.h).
 *   주의        : 이 함수가 끝날 때까지 loop() 가 멈춥니다(버튼은 "멈춤"으로만 읽음).
 *                 기다리는 동안 stepper·solenoid 가 linkPoll() 을 불러 시리얼 수신 버퍼를 비웁니다.
 */
bool punchBraille(const BrailleJob& job);

/*
 * 시험 라벨 한 장을 찍습니다 (USB 명령 T — 서버·ESP32 없이 기구만 확인할 때).
 *   1~6번째 칸 : 솔레노이드 1, 2, 3, 4, 5, 6 을 하나씩
 *   7번째 칸   : 6개 모두
 *   15번째 칸  : 6개 모두 (마지막 칸 자리 = 카드 반대쪽 여백 확인)
 * 돌려주는 값은 punchBraille 과 같습니다.
 */
bool punchTestLabel();

#endif  // PUNCH_H
