/*
 * Eye 2 Dot — 펌웨어 2 (책 점역기)
 * pins.h — 핀 번호 상수 모음 (팀 공용)
 *
 * ※ 초안입니다. firmware2/펌웨어2_부품목록.md "5-1. 아두이노 메가 핀"(11/3)을 옮겼습니다.
 *   - 솔레노이드(D22~D27)는 펌웨어 1 과 같아서 확정으로 봅니다.
 *   - 스텝 모터·원점 스위치는 11/6 구조 변경(종이 = 세로(Y) 이송, 헤드 = 가로(X)만 이동) 전의 값이라
 *     스텝 모터 담당이 다시 정한 뒤 이 파일만 고치면 됩니다.
 * 배선이 바뀌면 이 파일만 고치면 모든 모듈에 반영됩니다. 각자 branch 에서 따로 고치면 합칠 때 충돌이 나니
 * 바꿀 때는 팀에 먼저 알려 주세요.
 *
 * 괄호 안의 PA0 같은 표기는 칩 내부 포트 이름입니다(데이터시트 표기).
 */

#ifndef PINS_H
#define PINS_H

#include <Arduino.h>

// ─────────────────────────────────────────────
// 쓰면 안 되는 핀
// ─────────────────────────────────────────────
// D0, D1 은 USB 시리얼(Serial)이 씁니다. 다른 용도로 쓰지 마세요.
// D18, D19 는 ESP32 통신(Serial1)이 씁니다.
// Timer0 설정을 바꾸면 millis(), delay() 가 망가집니다.
// (펌웨어 2 에는 스피커가 없어서 펌웨어 1 의 D9~D12·tone() 금지는 해당 없음)

// ─────────────────────────────────────────────
// 점자 셀 솔레노이드 6개 (담당: 세연) — 확정
// ─────────────────────────────────────────────
// 솔레노이드 1~6 = 핀 22~27 = PA0~PA5. PORTA 한 번 쓰기로 6개를 동시에 켭니다.
// 1번 = 위에서 볼 때 왼쪽 위. 1·2·3 왼쪽 열, 4·5·6 오른쪽 열 (위→아래).
// 배선은 펌웨어 1 과 같은 "한쪽 끝 구동":
//   D22~D25 → L298N #1 IN1~IN4 → OUT1~OUT4 → 솔레노이드 1~4
//   D26~D27 → L298N #2 IN1~IN2 → OUT1~OUT2 → 솔레노이드 5~6
//   솔레노이드의 다른 쪽 선은 모두 GND. ENA·ENB 점퍼는 꽂은 채로. #2 IN3·IN4 는 비워 둠
constexpr uint8_t PIN_SOL[6] = { 22, 23, 24, 25, 26, 27 };

// ─────────────────────────────────────────────
// 스텝 모터 (담당: 스텝 모터) — 초안, 다시 정할 것
// ─────────────────────────────────────────────
// A4988: STEP 펄스 하나에 한 스텝, DIR 방향, EN 은 LOW 일 때 켜짐
constexpr uint8_t PIN_X_STEP = 2;    // 헤드 가로(X) 이동
constexpr uint8_t PIN_X_DIR  = 5;
constexpr uint8_t PIN_Y_STEP = 3;    // 종이 세로(Y) 이송
constexpr uint8_t PIN_Y_DIR  = 6;
constexpr uint8_t PIN_MOTOR_EN = 8;  // A4988 EN 모두 같이

// ─────────────────────────────────────────────
// 원점 스위치 (INPUT_PULLUP, 눌리면 LOW) — 초안
// ─────────────────────────────────────────────
constexpr uint8_t PIN_X_HOME = 9;
constexpr uint8_t PIN_Y_HOME = 10;

// ─────────────────────────────────────────────
// ESP32 통신 (Serial1) — 배선 안내용 (코드는 Serial1 객체로 씀)
// ─────────────────────────────────────────────
//   ESP32 TX → D19(RX1) 직결,  D18(TX1) → 1kΩ/2kΩ 분압(약 3.3V) → ESP32 RX,  GND 공통
constexpr uint8_t PIN_LINK_RX = 19;
constexpr uint8_t PIN_LINK_TX = 18;

// 상태 표시
constexpr uint8_t PIN_LED = 13;   // 보드 내장 LED

#endif  // PINS_H
